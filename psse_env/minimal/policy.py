"""The model as a policy of the minimal environment.

The research Gemma policy (``psse_env.dagger.research_policy_factory``) with
one thing replaced: what it renders.  Loading, decoding, sampling, the record
of each generation that RL trains on, and the refusal of a prompt that does
not fit are that policy's, unchanged.  The prompt and the tool list come from
``psse_env.minimal.observation``, the functions the training rows were built
with, and the generated call is checked against those tools alone.

A prompt that does not fit the model's input is refused, never cut: an
observation here is the whole episode, and a cut one would be a different
observation.  The runner ends such an episode without a declaration.
"""
from __future__ import annotations

import copy
from pathlib import Path
from typing import Any, Mapping

from psse_env.dagger.observation_modes import COMPLETE_HISTORY, HISTORY_RECORD_KEY
from psse_env.dagger.research_policy_factory import (
    GenerationOptions,
    PromptLimitError,
    _CanonicalResearchNativePolicy,
    _load_research_bundle,
)
from psse_env.minimal import observation as view
from psse_env.sft.gates import GateError


class MinimalModelPolicy(_CanonicalResearchNativePolicy):
    """One tool call per observation of ``MinimalDiagnosisEnv``, generated by the research model."""

    def render_messages(self, observation: Mapping[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
        tools = view.tools(observation)
        parameters = {row["function"]["name"]: row["function"]["parameters"] for row in tools}
        return view.messages(observation), tools, parameters

    @staticmethod
    def _whole(observation: Mapping[str, Any]) -> dict[str, Any]:
        """The observation marked as a whole-history view, so the base policy refuses an oversized prompt instead of cutting it."""
        return {**copy.deepcopy(dict(observation)), HISTORY_RECORD_KEY: {"contract": COMPLETE_HISTORY}}

    def act(self, observation: Mapping[str, Any]) -> Any:
        """The generated call as ``{"tool", "arguments"}``, or the raw text when it is not one valid call."""
        from psse_env.dagger.release_factories import _validated_generated_action

        whole = self._whole(observation)
        text = self.generate_text(whole)
        parameters = self.render_messages(whole)[2]
        try:
            return _validated_generated_action(text, parameters)
        except GateError:
            return text


def minimal_policy_factory(adapter_path: str | Path, *, base_model: str | None = None, base_revision: str | None = None,
                           load_in_4bit: bool = True, local_files_only: bool = True, trust_remote_code: bool = False,
                           architecture: str | None = None, cache: bool = True,
                           generation: GenerationOptions | None = None) -> MinimalModelPolicy:
    """Load a research LoRA as a policy of the minimal environment (greedy unless ``generation`` says otherwise)."""
    bundle, identity = _load_research_bundle(
        adapter_path=adapter_path, base_model=base_model, base_revision=base_revision, load_in_4bit=load_in_4bit,
        local_files_only=local_files_only, trust_remote_code=trust_remote_code, prompt_profile=None, use_cache=cache,
        architecture=architecture,
    )
    return MinimalModelPolicy(bundle, architecture=str(identity.get("architecture") or ""), generation=generation)


__all__ = ["MinimalModelPolicy", "PromptLimitError", "minimal_policy_factory"]
